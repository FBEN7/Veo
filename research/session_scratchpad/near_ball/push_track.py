"""Push plan_v4's step 2 (addendum 2), the CPU kernel track_kernel.py: the
code under test (src/ constants.py, player_filter.py,
team_assignment_v2.py, with their sha256) goes up as veo-nearball-track-stage;
the kernel reads the GPU pass's output (kernel veo-nearball-detall), the
supervision wheel from veo-code and the videos and clip files from the
shot-clip datasets (M7 / M9: veo-st2-dev2, opened clips only).

    VEO_UNSEAL=... KAGGLE_API_TOKEN=... python push_track.py stage|kernel [--dry]
"""
import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT))
OWNER = "francoisbernard"
SEALED = {"128057", "132831"}
CLIP_DS = ["veo-st2-dev2", *[f"veo-st2-m5-b{i}" for i in range(4)], *[f"veo-st2-train-b{i}" for i in range(10)]]
CODE = ["src/__init__.py", "src/constants.py", "src/player_filter.py", "src/team_assignment_v2.py"]


def kernel7() -> str:
    """plan_v7's A': track_kernel.py's variant A, each unit at its own
    conf_player (profile.json of the original run), units with
    conf_player >= 0.10; nothing else changed (each edit must apply once)."""
    import os
    import pandas as pd
    st = pd.read_parquet(HERE / "stages.parquet")
    confs = {}
    for w in sorted(st.unit.unique()):
        run = Path(os.path.realpath(ROOT / f".cache/gpu_shots3/{w}/output_{w}/metric_v3s_link.parquet")).parent
        c = float(json.loads((run / "shots_v3s_link/profile.json").read_text())["conf_player"])
        if c >= 0.10:
            confs[w] = c
    assert len(confs) == 221, len(confs)
    src = (HERE / "track_kernel.py").read_text()
    edits = [
        ("stage, det_dir, part, parts = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4])\n",
         "stage, det_dir, part, parts = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4])\n"
         "CONFS = json.load(open('/kaggle/working/confs.json'))   # plan_v7: each unit's conf_player\n"),
        ('units = open(f"{det_dir}/units.txt").read().split()[part::parts]',
         "units = sorted(CONFS)[part::parts]"),
        ("    d = det[det.conf >= CONF]\n", "    d = det[det.conf >= CONFS[w]]\n"),
        ('    for v, every in (("A", False), ("B", True)):\n', '    for v, every in (("A", False),):\n'),
        ('            msg.append(cap_and_save(teamed, w, "A"))\n', '            msg.append(cap_and_save(teamed, w, "Ap"))\n'),
        ('        # check: the kept fit labels the long tracks as the pipeline did\n'
         '        if len(feats) >= T.N_CLUSTERS:\n'
         '            fc = fit_clusters(feats, core)\n'
         '            tm = teamed[teamed.cls == "player"].drop_duplicates("track_id").set_index("track_id").team\n'
         '            bad = sum(1 for t, f in feats.items() if label(fc, f, t in core) != tm.get(t))\n'
         '            msg.append(f"{v} fit check {bad}/{len(feats)} differ")\n'
         '        teamed2, n_short, n_feat = short_teams(video, teamed, feats, core, depth)\n'
         '        msg.append(f"{v} short tracks {n_short}, {n_feat} with a kit")\n'
         '        msg.append(cap_and_save(teamed2, w, "A2" if v == "A" else "B2"))\n', ""),
        ('PARTS = os.cpu_count() or 4\n',
         f'json.dump({json.dumps(confs)}, open("/kaggle/working/confs.json", "w"))\nPARTS = os.cpu_count() or 4\n'),
    ]
    for old, new in edits:
        assert src.count(old) == 1, old[:60]
        src = src.replace(old, new)
    head = ("# plan_v7 (generated by push_track.py kernel7 from track_kernel.py): variant A\n"
            "# at each unit's own conf_player; output trk/<unit>_Ap.parquet.\n")
    return head + src


def main():
    from src.unseal import unsealed

    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=["stage", "kernel", "kernel7"])
    ap.add_argument("--work", default=str(HERE / "push_track"))
    ap.add_argument("--dry", action="store_true")
    args = ap.parse_args()
    work = Path(args.work)
    slug = f"{OWNER}/veo-nearball-track-stage"
    if args.what == "stage":
        ds = work / "stage_ds"
        shutil.rmtree(ds, ignore_errors=True)
        ds.mkdir(parents=True)
        sha = {}
        for f in CODE[1:]:                      # flat; the kernel rebuilds src/
            shutil.copy(ROOT / f, ds / Path(f).name)
            sha[f] = hashlib.sha256((ROOT / f).read_bytes()).hexdigest()
        (ds / "track_stage.json").write_text(json.dumps({"plan": "near_ball plan_v4 + addenda 1, 2", "sha256": sha}, indent=1))
        (ds / "dataset-metadata.json").write_text(json.dumps(
            {"title": "veo-nearball-track-stage", "id": slug, "licenses": [{"name": "other"}]}))
        (HERE / "track_stage_sha256.json").write_text(json.dumps(sha, indent=1))
        print(sha)
        if not args.dry:
            subprocess.run(["kaggle", "datasets", "create", "-p", str(ds), ], check=True)
        return
    for m in sorted(SEALED):
        if not unsealed(m, "near_ball plan_v4 step 2: tracker variants on the opened M7 / M9 shot clips (Kaggle CPU)"):
            raise SystemExit("VEO_UNSEAL needed")
    kd = work / ("kernel" if args.what == "kernel" else "kernel7")
    shutil.rmtree(kd, ignore_errors=True)
    kd.mkdir(parents=True)
    name = "veo-nearball-track"
    if args.what == "kernel":
        shutil.copy(HERE / "track_kernel.py", kd / "kernel.py")
    else:
        name = "veo-nearball-track-v7"
        (kd / "kernel.py").write_text(kernel7())
    (kd / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{OWNER}/{name}", "title": name, "code_file": "kernel.py",
        "language": "python", "kernel_type": "script", "is_private": True,
        "enable_gpu": False, "enable_internet": False,
        "dataset_sources": [f"{OWNER}/veo-code", slug, *[f"{OWNER}/{d}" for d in CLIP_DS]],
        "competition_sources": [], "kernel_sources": [f"{OWNER}/veo-nearball-detall"]}, indent=1))
    if not args.dry:
        subprocess.run(["kaggle", "kernels", "push", "-p", str(kd)], check=True)


if __name__ == "__main__":
    main()
