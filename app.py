"""Flask backend for Veo match analysis dashboard.

Serves JSON APIs for match data and provides a simple web interface for coaches.
Database: SQLite (match.db generated by pipeline)
"""

import json
import sqlite3
from pathlib import Path
from datetime import datetime
from flask import Flask, render_template, jsonify, request, send_file
from flask_cors import CORS
import io

app = Flask(__name__, template_folder='templates', static_folder='static')
CORS(app)

DB_PATH = "output/match.db"

# ============================================================================
# Database Helpers
# ============================================================================

def get_db():
    """Get database connection."""
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn

def dict_from_row(row):
    """Convert sqlite3.Row to dict."""
    return dict(row) if row else None

# ============================================================================
# API Routes
# ============================================================================

@app.route('/')
def index():
    """Serve main dashboard."""
    return render_template('index.html')

@app.route('/api/health')
def health():
    """Health check."""
    db_exists = Path(DB_PATH).exists()
    return jsonify({
        'status': 'ok',
        'database': 'ready' if db_exists else 'not_found',
        'timestamp': datetime.now().isoformat()
    })

@app.route('/api/matches')
def get_matches():
    """List all matches in database."""
    try:
        conn = get_db()
        matches = conn.execute(
            "SELECT id, label, date, duration_s FROM matches ORDER BY date DESC"
        ).fetchall()
        conn.close()
        return jsonify([dict(m) for m in matches])
    except Exception as e:
        return jsonify({'error': str(e)}), 500

@app.route('/api/matches/<int:match_id>')
def get_match(match_id):
    """Get detailed match info."""
    try:
        conn = get_db()
        match = conn.execute(
            "SELECT * FROM matches WHERE id=?", (match_id,)
        ).fetchone()

        if not match:
            return jsonify({'error': 'Match not found'}), 404

        conn.close()
        return jsonify(dict(match))
    except Exception as e:
        return jsonify({'error': str(e)}), 500

@app.route('/api/matches/<int:match_id>/summary')
def get_match_summary(match_id):
    """Get match summary: possession, stats, events."""
    try:
        conn = get_db()

        # Team stats
        team_stats = conn.execute(
            "SELECT team, possession_pct, n_passes, n_shots, n_goals FROM team_stats WHERE match_id=?",
            (match_id,)
        ).fetchall()

        # Event counts
        event_counts = conn.execute(
            "SELECT event_type, COUNT(*) as count FROM events WHERE match_id=? GROUP BY event_type",
            (match_id,)
        ).fetchall()

        # Top performers
        top_players = conn.execute(
            """SELECT track_id, team, distance_m, max_speed_kmh, n_passes, n_shots
               FROM player_stats WHERE match_id=? ORDER BY distance_m DESC LIMIT 11""",
            (match_id,)
        ).fetchall()

        conn.close()

        return jsonify({
            'team_stats': [dict(t) for t in team_stats],
            'events': {row['event_type']: row['count'] for row in event_counts},
            'top_players': [dict(p) for p in top_players]
        })
    except Exception as e:
        return jsonify({'error': str(e)}), 500

