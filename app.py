@app.route('/api/matches/<int:match_id>/possession-timeline')
def get_possession_timeline(match_id):
    """Get possession over time (5-min windows)."""
    try:
        conn = get_db()

        # Get possessions and aggregate by time windows
        possessions = conn.execute(
            "SELECT team, start_time_s, duration_s FROM possessions WHERE match_id=? ORDER BY start_time_s",
            (match_id,)
        ).fetchall()

        conn.close()

        # Bin into 5-minute windows
        windows = {}
        window_size = 300  # 5 minutes

        for poss in possessions:
            team = poss['team']
            start = poss['start_time_s']
            duration = poss['duration_s'] or 0

            window_idx = int(start / window_size)
            key = window_idx * window_size

            if key not in windows:
                windows[key] = {'team_a': 0, 'team_b': 0}

            if team == 'team_a' or team == 'Team A':
                windows[key]['team_a'] += duration
            else:
                windows[key]['team_b'] += duration

        # Convert to list with percentages
        result = []
        for key in sorted(windows.keys()):
            total = windows[key]['team_a'] + windows[key]['team_b']
            if total > 0:
                result.append({
                    'time_min': key / 60,
                    'team_a_pct': (windows[key]['team_a'] / total) * 100,
                    'team_b_pct': (windows[key]['team_b'] / total) * 100,
                })

        return jsonify(result)
    except Exception as e:
        return jsonify({'error': str(e)}), 500

