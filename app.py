@app.route('/api/matches/<int:match_id>/export/pdf')
def export_pdf(match_id):
    """Export match report as PDF."""
    try:
        from reportlab.lib.pagesizes import letter, A4
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import inch
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak
        from reportlab.lib import colors

        conn = get_db()

        # Get match info
        match = conn.execute("SELECT * FROM matches WHERE id=?", (match_id,)).fetchone()
        team_stats = conn.execute("SELECT * FROM team_stats WHERE match_id=?", (match_id,)).fetchall()
        player_stats = conn.execute("SELECT * FROM player_stats WHERE match_id=? ORDER BY team, distance_m DESC", (match_id,)).fetchall()

        conn.close()

        # Create PDF
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=letter, topMargin=0.5*inch, bottomMargin=0.5*inch)
        story = []
        styles = getSampleStyleSheet()

        # Title
        title = Paragraph(f"<b>Match Analysis Report</b><br/>{match['label']}", styles['Heading1'])
        story.append(title)
        story.append(Spacer(1, 0.2*inch))

        # Team Summary Table
        team_data = [['Team', 'Possession %', 'Passes', 'Shots', 'Goals', 'Distance (km)']]
        for ts in team_stats:
            team_data.append([
                ts['team'],
                f"{ts['possession_pct']:.1f}%",
                str(ts['n_passes']),
                str(ts['n_shots']),
                str(ts['n_goals']),
                f"{ts['total_distance_km']:.1f}"
            ])

        team_table = Table(team_data, colWidths=[1.5*inch, 1.2*inch, 1*inch, 1*inch, 1*inch, 1.5*inch])
        team_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#2c3e50')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, 0), 11),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 12),
            ('BACKGROUND', (0, 1), (-1, -1), colors.beige),
            ('GRID', (0, 0), (-1, -1), 1, colors.black)
        ]))
        story.append(team_table)
        story.append(Spacer(1, 0.3*inch))

        # Player Stats
        story.append(Paragraph("<b>Top Players by Distance</b>", styles['Heading2']))
        story.append(Spacer(1, 0.15*inch))

        player_data = [['Track ID', 'Team', 'Distance (m)', 'Top Speed (km/h)', 'Passes', 'Shots']]
        for ps in player_stats[:15]:  # Top 15 players
            player_data.append([
                str(ps['track_id']),
                ps['team'],
                f"{ps['distance_m']:.0f}",
                f"{ps['top_speed_kmh']:.1f}",
                str(ps['n_passes']),
                str(ps['n_shots'])
            ])

        player_table = Table(player_data, colWidths=[1*inch, 1*inch, 1.2*inch, 1.5*inch, 0.8*inch, 0.8*inch])
        player_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#34495e')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, 0), 10),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 10),
            ('BACKGROUND', (0, 1), (-1, -1), colors.HexColor('#ecf0f1')),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.grey)
        ]))
        story.append(player_table)

        # Build PDF
        doc.build(story)
        buffer.seek(0)

        return send_file(
            buffer,
            mimetype='application/pdf',
            as_attachment=True,
            download_name=f"match_{match_id}_report.pdf"
        )
    except Exception as e:
        return jsonify({'error': str(e)}), 500

