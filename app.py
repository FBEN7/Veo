def _clubhouse_write_allowed():
    configured_key = app.config.get("CLUBHOUSE_ADMIN_KEY", "")
    supplied_key = request.headers.get("X-Clubhouse-Key", "")
    return bool(configured_key) and hmac.compare_digest(configured_key, supplied_key)


def _valid_matchup(payload):
    home_team = str(payload.get("home_team", "")).strip()
    away_team = str(payload.get("away_team", "")).strip()
    if not home_team or not away_team or home_team.casefold() == away_team.casefold():
        return None
    if len(home_team) > 80 or len(away_team) > 80:
        return None
    return home_team, away_team


